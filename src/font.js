const ADVANCE = 6.2; // in grid units, including the gap

export function textWidth(str, size) {
  const u = size / 6;
  return str.length > 0 ? (str.length * ADVANCE - (ADVANCE - 4)) * u : 0;
}

/**
 * Draws `str` with its baseline at `y`. `align` is -1 left, 0 centre, 1 right.
 */
export function drawText(rd, str, x, y, size, w, r, g, b, a = 1, align = -1) {
  const u = size / 6;
  let ox = x;
  if (align === 0) ox -= textWidth(str, size) * 0.5;
  else if (align === 1) ox -= textWidth(str, size);

  // The table is uppercase only, and an unknown glyph still advances -- so
  // lowercase input used to draw as blank space of exactly the right width,
  // invisible but still shoving its neighbours around. Fold it instead. Case
  // folding never changes the length, so textWidth agrees either way.
  const text = str.toUpperCase();

  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const glyph = G[ch];
    if (glyph) {
      for (let p = 0; p < glyph.length; p++) {
        const pl = glyph[p];
        for (let k = 0; k + 3 < pl.length; k += 2) {
          rd.line2(
            ox + pl[k] * u, y - pl[k + 1] * u,
            ox + pl[k + 2] * u, y - pl[k + 3] * u,
            w, r, g, b, a, a,
          );
        }
      }
    }
    ox += ADVANCE * u;
  }
}
